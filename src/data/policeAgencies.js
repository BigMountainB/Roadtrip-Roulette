const pad3 = (deg) => String(deg).padStart(3, '0');

/** Texture key for one jurisdiction frame. */
export function jurFrameKey(prefix, deg) { return `jur_${prefix}_${pad3(deg)}`; }

/** The 9 {key, path} pairs for one agency's sprite set (loader input). */
export function agencyTextureList(agencyId) {
  const a = POLICE_AGENCIES[agencyId];
  if (!a) return [];
  return POLICE_ANGLES.map(deg => ({
    key:  jurFrameKey(a.prefix, deg),
    path: `assets/cars/jurisdictions/${a.prefix}_spin_${pad3(deg)}.png`,
  }));
}

/** Agencies whose region contains `mile`, as [{id, weight}].  Never empty —
 *  WSP spans the whole route. */
export function agencyPoolAt(mile) {
  const pool = [];
  for (const [id, a] of Object.entries(POLICE_AGENCIES)) {
    let w = 0;
    for (const [from, to, weight] of a.regions) {
      if (mile >= from && mile < to) w = Math.max(w, weight);
    }
    if (w > 0) pool.push({ id, weight: w });
  }
  return pool.length ? pool : [{ id: 'washington_state_patrol', weight: 1 }];
}

/** Weighted pick of an agency id for a spawn at `mile`.  rng injectable for
 *  tests. */
export function pickAgencyId(mile, rng = Math.random) {
  const pool = agencyPoolAt(mile);
  let total = 0;
  for (const p of pool) total += p.weight;
  let r = rng() * total;
  for (const p of pool) { r -= p.weight; if (r <= 0) return p.id; }
  return pool[pool.length - 1].id;
}

/** Nearest angle available in an ordered candidate list. */
function nearestOf(deg, candidates) {
  let best = candidates[0], bd = Infinity;
  for (const c of candidates) {
    const d = Math.abs(c - deg);
    if (d < bd) { bd = d; best = c; }
  }
  return best;
}

/** Snap an arbitrary yaw (deg, 0=rear … 180=front) onto the ladder. */
export function nearestPoliceAngle(deg) { return nearestOf(deg, POLICE_ANGLES); }

const DEFAULT_META = { w: 768, h: 512, cx0: 0, cy0: 0, cx1: 1, cy1: 1, lb: null };

/**
 * The single angle resolver.  Returns a place()-compatible frame object:
 *   { key, widthScale, groundFrac, flipX:false, lb, meta, vehicleClass }
 * widthScale converts canvas width → stable CONTENT width (class scale ×
 * 1/contentFrac), groundFrac seats the content's true bottom on the road.
 *
 * Fallback order (a missing asset must never lose the cruiser):
 *   1. requested jurisdiction at the nearest available angle
 *   2. requested jurisdiction 000
 *   3. generic equivalent angle (SWAT set for agencyId 'swat')
 *   4. generic car_back_police
 * `has(key)` reports whether a texture is actually loaded right now.
 */
export function resolvePoliceSprite({ agencyId, angle = 0, has = () => true, flip = false }) {
  const deg = nearestPoliceAngle(Math.abs(angle));
  const isSwat = agencyId === 'swat';
  const agency = !isSwat ? POLICE_AGENCIES[agencyId] : null;
  const tryKeys = [];
  if (agency) {
    tryKeys.push({ key: jurFrameKey(agency.prefix, deg), cls: agency.vehicleClass,
                   ref: jurFrameKey(agency.prefix, 0) });
    tryKeys.push({ key: jurFrameKey(agency.prefix, 0),   cls: agency.vehicleClass,
                   ref: jurFrameKey(agency.prefix, 0) });
  }
  const genSet = isSwat ? SWAT_FRAMES : GENERIC_POLICE_FRAMES;
  const genCls = isSwat ? 'swat' : 'sedan';
  const genDeg = nearestOf(deg, Object.keys(genSet).map(Number));
  tryKeys.push({ key: genSet[genDeg], cls: genCls, ref: genSet[0] });
  tryKeys.push({ key: 'car_back_police', cls: 'sedan' });
  if (isSwat) tryKeys.push({ key: 'car_back_swat', cls: 'swat' });   // legacy art fallback

  for (const { key, cls, ref } of tryKeys) {
    if (!has(key)) continue;
    const meta = POLICE_SPRITE_META[key] ?? DEFAULT_META;
    // HEIGHT-normalized sizing (owner bug 2026-08-28 "cop cars change size
    // on the angled frames"): the old rule held content WIDTH constant, but
    // a yawing car legitimately gets WIDER on screen while its HEIGHT stays
    // put — width-normalizing shrank the whole car ~18% at 7° / ~28% at 12°.
    // Scale each frame so its content HEIGHT matches the set's 000 frame
    // (all canvases in a set share w/h, so the aspect term cancels):
    //   widthScale = cls × ch000 / (cw000 × ch)   — reduces to cls/cw at 0°.
    const refMeta = POLICE_SPRITE_META[ref ?? key] ?? meta;
    const cw0 = Math.max(0.05, refMeta.cx1 - refMeta.cx0);
    const ch0 = Math.max(0.05, refMeta.cy1 - refMeta.cy0);
    const ch  = Math.max(0.05, meta.cy1 - meta.cy0);
    return {
      key,
      widthScale: (VEHICLE_CLASS_SCALE[cls] ?? 1) * ch0 / (cw0 * ch),
      groundFrac: meta.cy1,          // content bottom = tire line
      // The steering set only exists in its native RIGHT-turn direction, so a
      // LEFT-turning unit mirrors it (owner 2026-08-28: one-direction art
      // "looks like it's turning right but the car drifts left" beat the old
      // no-mirroring rule; door/trunk decals at 7-12° are small enough).
      // Spin/PIT ladders still never pass flip — big mirrored lettering.
      flipX: !!flip && deg !== 0 && deg !== 180,
      lb: meta.lb ?? null,
      meta,
      vehicleClass: cls,
      angle: deg,
    };
  }
  // Nothing loaded at all — caller keeps its previous texture.
  return null;
}

